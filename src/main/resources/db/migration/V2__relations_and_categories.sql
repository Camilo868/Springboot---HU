-- V2__relations_and_categories.sql
-- Evolución del modelo relacional, soft delete y categorización

-- 1. Ampliación geográfica en sedes
ALTER TABLE venues ADD COLUMN ciudad VARCHAR(100) DEFAULT 'Sin Ciudad' NOT NULL;

-- 2. Soporte para borrado lógico (Soft Delete) y vínculo obligatorio a Venue
ALTER TABLE events ADD COLUMN activo BOOLEAN DEFAULT TRUE NOT NULL;
ALTER TABLE events ADD COLUMN venue_id BIGINT;

-- 3. Nueva entidad de clasificación: Categorías
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(300)
);

-- 4. Tabla intermedia relacional Many-to-Many
CREATE TABLE events_categories (
    event_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,
    PRIMARY KEY (event_id, category_id),
    CONSTRAINT fk_ec_event FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
    CONSTRAINT fk_ec_category FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE CASCADE
);

-- 5. Clave foránea entre Eventos y Sedes
ALTER TABLE events ADD CONSTRAINT fk_events_venue FOREIGN KEY (venue_id) REFERENCES venues(id);
